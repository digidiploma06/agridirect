"""Master data: crops, all 36 Maharashtra districts and one main mandi per district.

Loaded from catalogue_data.json, which is generated by tools/build_catalogue.py
(the same file is copied to frontend/lib/mock/catalogue.data.json). Edit the
tool, not the JSON."""
from __future__ import annotations

import json
from pathlib import Path

_DATA = json.loads((Path(__file__).with_name("catalogue_data.json")).read_text(encoding="utf-8"))
CROPS: list[dict] = _DATA["crops"]
DISTRICTS: list[dict] = _DATA["districts"]
MANDIS: list[dict] = _DATA["mandis"]

CROP_IDS = [c["id"] for c in CROPS]
_CROPS = {c["id"]: c for c in CROPS}
_DISTRICTS = {d["id"]: d for d in DISTRICTS}
_MANDIS = {m["id"]: m for m in MANDIS}


def get_crop(crop_id: str) -> dict | None:
    return _CROPS.get(crop_id)


def get_district(district_id: str) -> dict | None:
    return _DISTRICTS.get(district_id)


def get_mandi(mandi_id: str) -> dict | None:
    return _MANDIS.get(mandi_id)


def mandis_in_district(district_id: str) -> list[dict]:
    return [m for m in MANDIS if m["districtId"] == district_id]
